#!/usr/bin/env node
// Regenerates docs/PR_LEDGER.md from git history (ADR 0004 §7). Idempotent: whole file, every run.
// Rows = commits on main whose subject ends in "(#N)" (squash merges). Newest first.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const out = process.argv[2] ?? "docs/PR_LEDGER.md";
const log = execFileSync("git", ["log", "--first-parent", "--date=short", "--format=%H%x09%ad%x09%s", "main"], { encoding: "utf8" });
const rows = [];
for (const line of log.split("\n")) {
  if (!line) continue;
  const [sha, date, subject] = line.split("\t");
  const m = subject.match(/^(.*) \(#(\d+)\)$/);
  if (!m) continue;
  const files = execFileSync("git", ["show", "--stat", "--format=", sha], { encoding: "utf8" }).trim().split("\n").pop() ?? "";
  rows.push(`| ${date} | [#${m[2]}](../../pull/${m[2]}) | ${m[1].replace(/\|/g, "\\|")} | ${files.trim()} | \`git revert ${sha.slice(0, 7)}\` |`);
}
const md = `# PR Ledger\n\nGenerated by \`pnpm ledger\` (\`infra/pr-ledger.mjs\`) on every merge to \`main\`. Do not edit by hand (ADR 0004).\n\n| Date | PR | Title | Changed | Revert |\n|---|---|---|---|---|\n${rows.join("\n")}\n`;
writeFileSync(out, md);
console.log(`${rows.length} rows -> ${out}`);
